#!/bin/bash
# Turn in-between display scales (like 175% on a 3456x2234 panel) on or off.
#
# Hyprland normally only accepts a scale that divides the display into whole
# logical pixels, and rounds anything else to the nearest one that does. Its
# `debug:disable_scale_checks` option lifts that; it's written to a toggle file
# that Omarchy loads after monitors.lua (Hyprland applies monitor rules once the
# whole config has loaded, so the order is fine).
#
#   on   write the toggle file and lift the check right away
#   off  remove it, then round the focused display's scale to a clean one
#        through Omarchy's own command, which also saves it to monitors.lua
set -euo pipefail

toggle="$HOME/.local/state/omarchy/toggles/hypr/omarchestra-display.lua"

case "${1:-}" in
on)
  mkdir -p "$(dirname "$toggle")"
  cat >"$toggle" <<'EOF'
-- Generated by omarchestra: allow in-between display scales.
-- Delete this file and run `hyprctl reload` to go back to clean scales only.
hl.config({ debug = { disable_scale_checks = true } })
EOF
  [[ $(hyprctl eval 'hl.config({ debug = { disable_scale_checks = true } })' 2>&1) == ok ]]
  ;;
off)
  rm -f "$toggle"
  [[ $(hyprctl eval 'hl.config({ debug = { disable_scale_checks = false } })' 2>&1) == ok ]]
  current=$(hyprctl monitors -j | jq -er '.[] | select(.focused == true) | .scale')
  # Omarchy's command only takes 1–4; it rounds up to the nearest clean scale.
  current=$(awk -v s="$current" 'BEGIN { if (s < 1) s = 1; if (s > 4) s = 4; printf "%g", s }')
  omarchy-hyprland-monitor-scaling "$current"
  ;;
*)
  echo "Usage: set-display-fractional.sh on|off" >&2
  exit 1
  ;;
esac
