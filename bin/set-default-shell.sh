#!/bin/bash
# Reflect a newly chosen login shell into the running session. `chsh -s` only
# rewrites /etc/passwd; it does not touch the $SHELL variable that the live
# session already exported, so a new terminal keeps spawning the old shell
# until the next login. Terminals opened from a Hyprland keybind inherit
# Hyprland's environment, which is frozen at login, so the only way to reach
# them without logging out is `hl.env` in a hot-reloaded toggle file (see
# ~/.local/state/omarchy/toggles/hypr/*.lua and default/hypr/envs.lua — note
# that hyprctl setenv does not reach the keybind dispatcher env).
#
# Also mirror the value into the systemd user + D-Bus activation environments
# so apps launched outside Hyprland see it too.
set -euo pipefail

shell_path="${1:-}"
if [[ -z "$shell_path" ]]; then
  echo "usage: $0 <shell-path>" >&2
  exit 1
fi

state_dir="${XDG_STATE_HOME:-$HOME/.local/state}/omarchy/toggles/hypr"
mkdir -p "$state_dir"

{
  printf '%s\n' '-- Generated by omarchestra. Delete to restore Omarchy defaults.'
  printf 'hl.env("SHELL", "%s")\n' "$shell_path"
} > "$state_dir/shell.lua"

# A newly-created (or just-removed) toggle file is not hot-reloaded on its own.
hyprctl reload >/dev/null 2>&1 || true

systemctl --user set-environment SHELL="$shell_path"
dbus-update-activation-environment --systemd SHELL="$shell_path"
