#!/bin/bash
# Install or remove omarchestra's lid-close handler so "When lid is closed →
# Do nothing" actually suppresses Omarchy's lock-on-close.
#
# Omarchy locks on lid close via a Hyprland switch binding
# (switch:on:Lid Switch → omarchy-system-lid-close), independent of the
# systemd-logind drop-in that set-power-settings.sh writes. For lock/suspend/
# hibernate/poweroff that binding already does the right thing (lock, or
# lock-before-suspend), so this only overrides it when an "ignore" (Do nothing)
# action needs the lock dropped. Run as the user (no root).
set -euo pipefail

battery_action="${1:-ignore}"
ac_action="${2:-ignore}"

for a in "$battery_action" "$ac_action"; do
  case "$a" in ignore|lock|suspend|hibernate|poweroff) ;; *) echo "bad lid action: $a" >&2; exit 2 ;; esac
done

toggles_dir="$HOME/.local/state/omarchy/toggles/hypr"
toggle="$toggles_dir/lid-close.lua"
plugin_dir="$(cd "$(dirname "$0")/.." && pwd)"
# plugin_dir is a fixed install path with no quotes or spaces, so it can be
# embedded verbatim inside a single-quoted shell string below.
handler="$plugin_dir/bin/lid-close.sh"

if [[ "$battery_action" == "ignore" || "$ac_action" == "ignore" ]]; then
  content=$(cat <<EOF
-- Generated by omarchestra. Delete to restore Omarchy's lid-close lock.
hl.unbind("switch:on:Lid Switch")
hl.bind("switch:on:Lid Switch", hl.dsp.exec_cmd("bash '$handler'"), { locked = true })
EOF
)
else
  content=""
fi

current=""
[[ -f "$toggle" ]] && current="$(cat "$toggle")"

if [[ "$content" != "$current" ]]; then
  if [[ -z "$content" ]]; then
    rm -f "$toggle"
  else
    mkdir -p "$toggles_dir"
    printf '%s\n' "$content" > "$toggle"
  fi
  hyprctl reload >/dev/null 2>&1 || true
fi
